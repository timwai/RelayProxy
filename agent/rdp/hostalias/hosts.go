// Package hostalias manages friendly local names for RDP loopback listeners.
// Hosts records are intentionally persistent, so reconnecting the same device
// does not require another privilege prompt. Only RelayProxy-prefixed local
// aliases are written; existing hosts records are never overwritten.
package hostalias

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"

	"golang.org/x/net/idna"
)

const aliasPrefix = "relayproxy-"

// Each alias is a single DNS label instead of a *.test hostname. Keep its
// total length below 63 bytes including the stable device-ID hash.
var validAlias = regexp.MustCompile(`^relayproxy-[a-z0-9][a-z0-9-]{0,39}-[a-f0-9]{8}$`)

// Alias creates a deterministic DNS label from a device name and identity.
// The ID checksum keeps separate devices with the same display name distinct.
func Alias(name, deviceID string) string {
	label := strings.ToLower(strings.TrimSpace(name))
	label = strings.Join(strings.Fields(label), "-")
	if ascii, err := idna.Lookup.ToASCII(label); err == nil {
		label = ascii
	}
	var out strings.Builder
	for _, ch := range label {
		if (ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9') || ch == '-' {
			out.WriteRune(ch)
		} else if out.Len() > 0 {
			out.WriteByte('-')
		}
		if out.Len() >= 40 {
			break
		}
	}
	label = strings.Trim(out.String(), "-")
	if label == "" {
		label = "device"
	}
	hash := sha256.Sum256([]byte(deviceID))
	return aliasPrefix + label + "-" + hex.EncodeToString(hash[:4])
}

// Ensure adds one canonical hosts record and returns its DNS name. A denied
// administrator prompt is reported to the caller, which should use 127.0.0.1.
func Ensure(name, deviceID string) (string, error) {
	if strings.TrimSpace(deviceID) == "" {
		return "", errors.New("missing RDP device identity")
	}
	alias := Alias(name, deviceID)
	err := writeHosts(hostsPath(), alias)
	if err != nil && os.IsPermission(err) {
		if elevationErr := elevate(alias); elevationErr != nil {
			return "", fmt.Errorf("hosts 需要管理员权限: %w", elevationErr)
		}
		// Re-read after privileged helper. Never claim a hostname was installed
		// solely because the elevation process exited with status zero.
		if verifyErr := verifyHosts(hostsPath(), alias); verifyErr != nil {
			return "", verifyErr
		}
		return alias, nil
	}
	if err != nil {
		return "", err
	}
	return alias, nil
}

// RunHelper is used only by the admin-elevated copy of relay-agent. It rejects
// arbitrary hostnames, IPs and paths before touching the system hosts file.
func RunHelper(alias string) error {
	if !validAlias.MatchString(alias) {
		return errors.New("invalid RelayProxy RDP hosts alias")
	}
	return writeHosts(hostsPath(), alias)
}

func hostsPath() string {
	switch runtime.GOOS {
	case "windows":
		root := os.Getenv("SystemRoot")
		if root == "" {
			root = `C:\Windows`
		}
		return filepath.Join(root, "System32", "drivers", "etc", "hosts")
	default:
		return "/etc/hosts"
	}
}

func inspectHosts(data []byte, alias string) (bool, error) {
	found := false
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(strings.SplitN(line, "#", 2)[0])
		if len(fields) < 2 {
			continue
		}
		for _, host := range fields[1:] {
			if !strings.EqualFold(host, alias) {
				continue
			}
			if fields[0] != "127.0.0.1" {
				return false, fmt.Errorf("hosts name %q already maps to %s", alias, fields[0])
			}
			found = true
		}
	}
	return found, nil
}

func verifyHosts(path, alias string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	found, err := inspectHosts(data, alias)
	if err != nil {
		return err
	}
	if !found {
		return fmt.Errorf("hosts alias %s not present after update", alias)
	}
	return nil
}

// legacyAlias is derived from our previous autogenerated *.relayproxy.test
// format. It is not accepted as a new alias by the privileged helper.
func legacyAlias(alias string) string {
	if !validAlias.MatchString(alias) {
		return ""
	}
	return strings.TrimPrefix(alias, aliasPrefix) + ".relayproxy.test"
}

// updateHosts changes only one exact RelayProxy-managed legacy entry, if
// present. Other hosts records, their order and line endings remain unchanged.
func updateHosts(data []byte, alias string) ([]byte, bool, error) {
	if !validAlias.MatchString(alias) {
		return nil, false, errors.New("unsafe RDP hosts alias")
	}
	found, err := inspectHosts(data, alias)
	if err != nil {
		return nil, false, err
	}
	old := legacyAlias(alias)
	lines := strings.SplitAfter(string(data), "\n")
	var out strings.Builder
	migrated := false
	for _, line := range lines {
		content := strings.TrimRight(line, "\r\n")
		fields := strings.Fields(content)
		if len(fields) == 5 && fields[0] == "127.0.0.1" && strings.EqualFold(fields[1], old) &&
			fields[2] == "#" && fields[3] == "RelayProxy" && fields[4] == "RDP" {
			migrated = true
			if found {
				continue // Remove only our exact obsolete entry.
			}
			// Preserve the line ending and replace just the old hostname.
			line = strings.Replace(line, fields[1], alias, 1)
			found = true
		}
		out.WriteString(line)
	}
	if !found {
		newline := "\n"
		if strings.Contains(string(data), "\r\n") {
			newline = "\r\n"
		}
		if len(data) > 0 && data[len(data)-1] != '\n' {
			out.WriteString(newline)
		}
		out.WriteString("127.0.0.1 " + alias + " # RelayProxy RDP" + newline)
	}
	result := []byte(out.String())
	changed := migrated || !bytes.Equal(result, data)
	return result, changed, nil
}

func writeHosts(path, alias string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	updated, changed, err := updateHosts(data, alias)
	if err != nil || !changed {
		return err
	}
	// Reuse the original inode and ACL rather than replacing system hosts with
	// a temp file. O_RDWR requires elevation when the caller cannot modify it.
	file, err := os.OpenFile(path, os.O_RDWR, 0)
	if err != nil {
		return err
	}
	defer file.Close()
	if _, err = file.WriteAt(updated, 0); err != nil {
		return err
	}
	if err = file.Truncate(int64(len(updated))); err != nil {
		return err
	}
	return file.Sync()
}

// elevate uses the running binary itself as a narrowly scoped privileged
// helper. No mutable temporary scripts or user-provided shell commands.
func elevate(alias string) error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	arg := "--_rdp-hosts-add=" + alias
	switch runtime.GOOS {
	case "windows":
		return elevateWindows(exe, arg)
	case "darwin":
		shellQuote := func(s string) string { return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'" }
		command := shellQuote(exe) + " " + shellQuote(arg)
		appleQuote := "\"" + strings.ReplaceAll(strings.ReplaceAll(command, "\\", "\\\\"), "\"", "\\\"") + "\""
		out, e := exec.Command("/usr/bin/osascript", "-e", "do shell script "+appleQuote+" with administrator privileges").CombinedOutput()
		if e != nil {
			return fmt.Errorf("macOS 管理员授权: %w (%s)", e, strings.TrimSpace(string(out)))
		}
		return nil
	default:
		out, e := exec.Command("pkexec", exe, arg).CombinedOutput()
		if e != nil {
			return fmt.Errorf("无法通过 pkexec 修改 hosts: %w (%s)", e, strings.TrimSpace(string(out)))
		}
		return nil
	}
}
